/**
 * Copies the PHP package's translations into `lang/<locale>.json`, flattened to
 * dot keys (LocaleService::messagesFor), and writes `lang/index.ts` importing
 * every locale. The PHP files stay the source; rerun after they change:
 * `bun run sync:lang` (needs `php` on PATH). `--check` writes nothing and
 * fails when a file is stale or missing.
 */
import { existsSync, readdirSync, readFileSync } from "node:fs";

const SOURCE = `${import.meta.dir}/../../php/resources/lang`;
const TARGET = `${import.meta.dir}/../lang`;

type Tree = { [key: string]: string | Tree };

function flatten(tree: Tree, prefix = ""): Record<string, string> {
	const out: Record<string, string> = {};
	for (const [key, value] of Object.entries(tree)) {
		const dotted = prefix === "" ? key : `${prefix}.${key}`;
		Object.assign(
			out,
			typeof value === "string" ? { [dotted]: value } : flatten(value, dotted),
		);
	}
	return out;
}

async function load(file: string): Promise<Tree> {
	const php = Bun.spawn(["php", "-r", "echo json_encode(require $argv[1]);", file]);
	const json = await new Response(php.stdout).text();
	if ((await php.exited) !== 0) {
		throw new Error(`php failed on ${file}`);
	}
	return JSON.parse(json) as Tree;
}

const check = process.argv.includes("--check");
const locales = readdirSync(SOURCE).sort();
const files: Record<string, string> = {};
for (const locale of locales) {
	const messages = flatten(await load(`${SOURCE}/${locale}/admin.php`));
	files[`${locale}.json`] = `${JSON.stringify(messages, null, "\t")}\n`;
}
files["index.ts"] = [
	"// Generated by `bun run sync:lang`; do not edit.",
	...locales.map((locale) => `import ${ident(locale)} from "./${locale}.json";`),
	"",
	`export default { ${locales.map((l) => `${key(l)}: ${ident(l)}`).join(", ")} };`,
	"",
].join("\n");

/** An object key as the formatter writes it: quoted only when it must be. */
function key(locale: string): string {
	return /^[A-Za-z_$][\w$]*$/.test(locale) ? locale : JSON.stringify(locale);
}

function ident(locale: string): string {
	return `lang_${locale.replaceAll(/\W/g, "_")}`;
}

const stale = Object.entries(files).filter(
	([name, text]) =>
		!existsSync(`${TARGET}/${name}`) || readFileSync(`${TARGET}/${name}`, "utf8") !== text,
);
if (check) {
	for (const [name] of stale) {
		console.error(`lang/${name} is out of date with the PHP lang files: run bun run sync:lang`);
	}
	process.exit(stale.length === 0 ? 0 : 1);
}
for (const [name, text] of stale) {
	await Bun.write(`${TARGET}/${name}`, text);
	console.log(`lang/${name} written`);
}
