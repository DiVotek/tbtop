// Pulls the upstream shadcn style presets into src/ui/presets/ and writes one
// entry per style to src/styles/. Each preset is upstream
// `apps/v4/registry/styles/style-<name>.css` with the root scope renamed
// `.style-<name>` → `.style-preset-<name>` (no clash with a host's own shadcn)
// and only the SECTIONS the client renders; kept sections are verbatim.
// Refresh: bump UPSTREAM_REF, run `bun scripts/sync-presets.ts`, review the
// diff. A component that starts using a new upstream section adds it to
// SECTIONS. A new style goes in STYLE_PRESETS (src/app/appearance.ts) and
// PHP's ConfiguresAppearance::STYLE_PRESETS; styles.test.ts checks both, but
// styles.css's import list is edited by hand. tbtop-only rules: tbtop.css.
import { mkdir } from "node:fs/promises";
import { STYLE_PRESETS as STYLES } from "../src/app/appearance";

const UPSTREAM_REF = "c2477f311c19982ef6e246085438e6cfec3e35ea";

// Upstream `/* MARK: <name> */` sections the client's `cn-*` classes use.
const SECTIONS = new Set([
	"Alert",
	"Badge",
	"Button",
	"Calendar",
	"Card",
	"Checkbox",
	"Command",
	"Dialog",
	"Drawer",
	"Dropdown Menu",
	"Empty",
	"Input",
	"Input Group",
	"Input OTP",
	"Label",
	"Popover",
	"Progress",
	"Radio Group",
	"Select",
	"Sidebar",
	"Slider",
	"Switch",
	"Table",
	"Tabs",
	"Textarea",
	"Toggle",
	"Toggle Group",
	"Tooltip",
]);

const base = `https://raw.githubusercontent.com/shadcn-ui/ui/${UPSTREAM_REF}/apps/v4/registry/styles`;
const outDir = `${import.meta.dir}/../src/ui/presets`;
const entryDir = `${import.meta.dir}/../src/styles`;

function header(name: string): string {
	return [
		"/* Generated by scripts/sync-presets.ts — do not edit by hand.",
		` * Upstream: shadcn-ui/ui@${UPSTREAM_REF.slice(0, 12)} apps/v4/registry/styles/style-${name}.css`,
		` * Scope renamed .style-${name} → .style-preset-${name}; unused sections dropped. */`,
		"/* biome-ignore-all format: upstream file, kept verbatim */",
		"",
	].join("\n");
}

async function fetchStyle(name: string): Promise<string> {
	const res = await fetch(`${base}/style-${name}.css`);
	if (!res.ok) {
		throw new Error(`style-${name}.css: HTTP ${res.status}`);
	}
	const css = await res.text();
	const scope = `.style-${name} {`;
	if (!css.startsWith(scope)) {
		throw new Error(`style-${name}.css no longer opens with "${scope}"`);
	}
	return keepSections(css.replace(scope, `.style-preset-${name} {`));
}

/** Drops every `/* MARK: X *\/` section whose name is not in SECTIONS. */
function keepSections(css: string): string {
	// Peel the scope's closing brace first so it survives a dropped last section.
	const inner = css.trimEnd().replace(/\}$/, "");
	const parts = inner.split(/(?=^ {2}\/\* MARK: )/m);
	const kept = parts.filter((part, i) => {
		const mark = part.match(/^ {2}\/\* MARK: (.+?) \*\//);
		return i === 0 || (mark !== null && SECTIONS.has(mark[1]));
	});
	return `${kept.join("").trimEnd()}\n}\n`;
}

/** A single-style entry: core + one preset, for hosts that pin one style. */
function entry(name: string): string {
	return [
		"/* Generated by scripts/sync-presets.ts. Core styles + the one style preset. */",
		'@import "../core.css";',
		`@import "../ui/presets/style-preset-${name}.css" layer(components);`,
		'@import "../ui/presets/tbtop.css" layer(components);',
		"",
	].join("\n");
}

await mkdir(outDir, { recursive: true });
await mkdir(entryDir, { recursive: true });
for (const name of STYLES) {
	const css = await fetchStyle(name);
	await Bun.write(`${outDir}/style-preset-${name}.css`, header(name) + css);
	await Bun.write(`${entryDir}/${name}.css`, entry(name));
	console.log(`style-preset-${name}.css, styles/${name}.css`);
}
